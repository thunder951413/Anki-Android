const tables = { zh, en };

function detect() {
    const query = globalThis.location?.search ? new URLSearchParams(globalThis.location.search).get("lang") : null;
    const language = (query || globalThis.navigator?.language || "zh").toLowerCase();
    return language.startsWith("zh") ? "zh" : "en";
}

let current = detect();

export function setLocale(language) {
    current = String(language).toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function locale() {
    return current === "zh" ? "zh-CN" : "en";
}

/** Looks up [key], falling back to Chinese, and fills `{name}` placeholders. */
export function t(key, params = {}) {
    const template = tables[current][key] ?? zh[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

